inline void drawFursonaLogo(TFT_eSPI &display, int x, int y) {
    uint16_t lineBuf[FURSONA_LOGO_W];
    bool prevSwap = display.getSwapBytes();
    display.setSwapBytes(true);
    for (int r = 0; r < FURSONA_LOGO_H; r++) {
        for (int c = 0; c < FURSONA_LOGO_W; c++) {
            uint8_t palIdx = pgm_read_byte(&FURSONA_PIXELS[r * FURSONA_LOGO_W + c]);
            lineBuf[c] = pgm_read_word(&FURSONA_PALETTE[palIdx]);
        }
        display.pushImage(x, y + r, FURSONA_LOGO_W, 1, lineBuf);
    }
    display.setSwapBytes(prevSwap);
}

